/** Fast lookup by id, with a guaranteed fallback to the default theme. */
export const THEME_BY_ID: Record<string, Theme> = Object.fromEntries(
  THEMES.map((t) => [t.id, t]),
);

/** The default theme, resolved once. Guaranteed present in `THEMES`. */
const DEFAULT_THEME: Theme =
  THEMES.find((t) => t.id === DEFAULT_THEME_ID) ?? THEMES[0]!;

export function getTheme(id: string | undefined | null): Theme {
  if (id) {
    const found = THEME_BY_ID[id];
    if (found) return found;
  }
  return DEFAULT_THEME;
}
